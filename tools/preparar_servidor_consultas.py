#!/usr/bin/env python3
"""Produce one dependency-free Worker file for Cloudflare's dashboard editor."""
from pathlib import Path
import re
import shutil
import subprocess
import zipfile

root = Path(__file__).resolve().parents[1]
server = root / 'consultas-api'
out = server / 'dist'
out.mkdir(exist_ok=True)
modules = [
    ('Security', 'security.mjs', 'ApiError, deny, nowSeconds, base64url, decode64, randomToken, hash, validToken, same, verifyGoogleIdToken, limitedJson'),
    ('Sheets', 'sheets.mjs', 'readCatalog, readAuthorizedLoans, todayLima, sheetsApi, SheetsFailure, dateValue'),
    ('Directory', 'directory.mjs', 'ClientDirectory, importClientDirectory, newCustomerCode, CLIENT_CODE'),
    ('Registry', 'registry.mjs', 'SheetsRegistry, purgeExpired'),
    ('Privacy', 'privacy.mjs', 'publicPage'),
]
def imports(text):
    for source, name in [('security', 'Security'), ('sheets', 'Sheets'), ('privacy', 'Privacy'), ('registry', 'Registry'), ('directory', 'Directory')]:
        text = re.sub(r'import \{([^}]+)\} from "\./' + source + r'\.mjs";', lambda match: 'const {' + match[1] + '} = ' + name + ';', text)
    return text

chunks = ['// Generated by tools/preparar_servidor_consultas.py. No secrets included.\n']
for name, filename, exports in modules:
    source = imports((server / 'src' / filename).read_text())
    source = re.sub(r'^export ', '', source, flags=re.MULTILINE)
    chunks.append(f'const {name} = (() => {{\n{source}\nreturn {{{exports}}};\n}})();\n')
entry = imports((server / 'src/worker.mjs').read_text())
# Export only the Worker entrypoint; the injectable factory remains available in
# src/worker.mjs for local tests, not as a Cloudflare service entrypoint.
entry = re.sub(r'^export function createHandler', 'function createHandler', entry, flags=re.MULTILINE)
chunks.append(entry)
bundle = out / 'worker.mjs'
bundle.write_text('\n'.join(chunks))
shutil.copyfile(bundle, out / 'COPIAR_EN_CLOUDFLARE.txt')
subprocess.run(['node', '--check', bundle], check=True)
print(bundle)
print(out / 'COPIAR_EN_CLOUDFLARE.txt')
